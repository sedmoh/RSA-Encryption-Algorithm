# ---------- Primality (Miller-Rabin) ----------

@pytest.mark.parametrize("p", [2, 3, 5, 7, 13, 97, 7919, 104729, 2**31 - 1, 2**61 - 1, 2**127 - 1])
def test_known_primes_are_prime(p):
    assert rsa.is_prime(p)


@pytest.mark.parametrize("n", [-7, 0, 1, 4, 9, 15, 221, 7917, 2**32 + 1, 2**61 + 1])
def test_known_composites_are_not_prime(n):
    assert not rsa.is_prime(n)


@pytest.mark.parametrize("n", [561, 1105, 1729, 2465, 2821, 6601, 8911])
def test_carmichael_numbers_are_not_prime(n):
    #these fool the plain Fermat test for every base coprime to n. Miller-Rabin must reject them.
    assert not rsa.is_prime(n, k=20)


@pytest.mark.parametrize("bits", [16, 64, 128])
def test_generate_prime_has_exact_bit_length_and_is_odd(bits):
    p = rsa.generate_prime(bits)
    assert p.bit_length() == bits
    assert p % 2 == 1
    assert rsa.is_prime(p, k=20)


# ---------- HCF, extended Euclid, modular inverse ----------

@pytest.mark.parametrize("a, b, expected", [(48, 18, 6), (240, 46, 2), (17, 5, 1), (100, 10, 10), (7, 0, 7)])
def test_hcf(a, b, expected):
    assert rsa.hcf(a, b) == expected


@pytest.mark.parametrize("a, b", [(240, 46), (7, 40), (65537, 3120), (12345, 54321)])
def test_extended_hcf_satisfies_bezout_identity(a, b):
    g, x, y = rsa.extended_hcf(a, b)
    assert g == rsa.hcf(a, b)
    assert a * x + b * y == g


def test_mod_inverse_matches_worked_example():
    #the inverse of 7 mod 40 is 23.
    assert rsa.mod_inverse(7, 40) == 23


@pytest.mark.parametrize("e, phi", [(3, 40), (17, 3120), (65537, 2**64 - 59)])
def test_mod_inverse_property(e, phi):
    d = rsa.mod_inverse(e, phi)
    assert 0 <= d < phi
    assert (e * d) % phi == 1


def test_mod_inverse_raises_when_not_coprime():
    with pytest.raises(ValueError):
        rsa.mod_inverse(4, 40)


# ---------- Key generation ----------

def test_keypair_shares_modulus_and_has_expected_size(keypair):
    (e, n), (d, n2) = keypair
    assert n == n2
    #two 256-bit primes give a modulus of 511 or 512 bits.
    assert 2 * TEST_BITS - 1 <= n.bit_length() <= 2 * TEST_BITS
    assert 1 < e < n and 1 < d < n


def test_encrypt_then_decrypt_returns_original_numbers(keypair):
    public, private = keypair
    n = public[1]
    rng = random.Random(0)  #fixed seed so a failure can be reproduced
    messages = [0, 1, 2, n - 1] + [rng.randrange(n) for _ in range(200)]
    for m in messages:
        assert rsa.decrypt(rsa.encrypt(m, public), private) == m


def test_decrypt_then_encrypt_also_round_trips(keypair):
    #RSA works in both directions, which is the basis of digital signatures.
    public, private = keypair
    m = 123456789
    assert rsa.encrypt(rsa.decrypt(m, private), public) == m


def test_message_too_large_raises(keypair):
    public, _ = keypair
    n = public[1]
    with pytest.raises(ValueError):
        rsa.encrypt(n, public)
    with pytest.raises(ValueError):
        rsa.encrypt(n + 1, public)


def test_different_keys_each_time():
    (_, n1), _ = rsa.generate_keypair(64)
    (_, n2), _ = rsa.generate_keypair(64)
    assert n1 != n2


# ---------- Text conversion ----------

@pytest.mark.parametrize("text", ["hello, my name is john", "A", "", "café ☕", "مرحبا"])
def test_text_round_trips_through_integers(text):
    assert rsa.int_to_text(rsa.text_to_int(text)) == text


def test_full_text_encryption_round_trip(keypair):
    public, private = keypair
    text = "hello, my name is john"
    m = rsa.text_to_int(text)
    assert rsa.int_to_text(rsa.decrypt(rsa.encrypt(m, public), private)) == text


# ---------- Security: keys must not come from a predictable generator ----------

def test_keys_do_not_depend_on_the_random_module_seed():
    #python's random module is predictable. If keys come from it, seeding it
    #identically produces identical "secret" keys. With the secrets module they differ.
    random.seed(1234)
    first = rsa.generate_keypair(64)
    random.seed(1234)
    second = rsa.generate_keypair(64)
    assert first != second, "Keys are reproducible from random.seed(): use the secrets module"
